export function calculateWhatIfMetrics(params: {
  missingInfoPercent?: number;
  noiseLevel?: 'low' | 'medium' | 'high' | number;
  populationShiftPercent?: number;
  device?: 'Device A' | 'Device B' | boolean;
  missingPct?: number;
  popShiftLevel?: number;
  targetDevice?: boolean;
}) {
  const baseline = 94;

  const missing = params.missingInfoPercent !== undefined ? params.missingInfoPercent : (params.missingPct ?? 0);
  const popShift = params.populationShiftPercent !== undefined ? params.populationShiftPercent : (params.popShiftLevel ?? 0);
  const isDeviceB = params.device !== undefined ? params.device === 'Device B' : Boolean(params.targetDevice);
  
  let noiseNum = 20;
  if (typeof params.noiseLevel === 'number') {
    noiseNum = params.noiseLevel;
  } else if (params.noiseLevel === 'high') {
    noiseNum = 80;
  } else if (params.noiseLevel === 'medium') {
    noiseNum = 50;
  } else {
    noiseNum = 15;
  }

  // Non-linear penalties
  const missingPenalty = (missing / 30) * 14;
  const noisePenalty = (noiseNum / 100) * 8;
  const popPenalty = (popShift / 40) * 15;
  const devicePenalty = isDeviceB ? 18 : 0;

  // Synergistic compound penalty if 2 or more stressors are active
  const activeCount =
    (missing > 10 ? 1 : 0) +
    (noiseNum > 30 ? 1 : 0) +
    (popShift > 15 ? 1 : 0) +
    (isDeviceB ? 1 : 0);

  const synergyPenalty = activeCount >= 3 ? 9 : activeCount >= 2 ? 4 : 0;

  const simulatedScore = Math.max(
    48,
    Math.round(baseline - missingPenalty - noisePenalty - popPenalty - devicePenalty - synergyPenalty)
  );

  const performanceDrop = baseline - simulatedScore;

  let trustZone: 'GREEN' | 'YELLOW' | 'RED' = 'GREEN';
  if (simulatedScore < 75 || activeCount >= 2 || isDeviceB) {
    trustZone = 'RED';
  } else if (simulatedScore < 85 || activeCount >= 1) {
    trustZone = 'YELLOW';
  }

  const safeToDeploy = trustZone !== 'RED';

  return {
    baseline,
    simulatedScore,
    predictedPerformance: simulatedScore,
    drop: performanceDrop,
    performanceDrop,
    activeStressors: activeCount,
    trustZone,
    synergyPenalty,
    safeToDeploy,
  };
}
